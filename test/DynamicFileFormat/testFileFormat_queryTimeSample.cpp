// Instead of baking the whole timeline when the payload layer is read, the
// Dynamic File Format exposes a lazy SdfAbstractData that evaluates the
// Bifrost graph at the time sample(s) USD queries. These tests exercise that
// behavior through the public Usd API: time sample discovery, per-time values,
// the untimed (default) value, and per-time caching.

