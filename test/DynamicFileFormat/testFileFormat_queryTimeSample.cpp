// The tests are using the move_up_point_simulation compound that moves a point
// up the Y axis by a `vertical_step' units per frame. At the first frame the
// point is at (0,0,0), and at frame N it is at (0, (N - startFrame) *
// verticalStep, 0). The fps (frame per second) variable is set to 1.0 so the
// per-frame increment equals verticalStep.
constexpr double kStartFrame = 1.0;
constexpr double kEndFrame   = 3.0;

// Count how many times the graph reported (re-)evaluating a given frame. The
// executeGraph step emits a "Set frame <f> in graph ..." status at the most
// verbose level, so the occurrence count is the number of executions of that
// frame. Frames are formatted as doubles ("Set frame 2.000000"), so match on
// that exact form to avoid e.g. "Set frame 2" also matching frame 20.
size_t countSetFrame(const PXR_NS::DffDiagnosticCollector& collector,
                     const std::string&                    bucketKey,
                     double                                frame) {
    const std::string needle = "Set frame " + std::to_string(frame);
    size_t            count  = 0;
    for (const auto& msg : dffGetStatusMessages(collector, bucketKey)) {
        if (msg.find(needle) != std::string::npos) {
            ++count;
        }
    }
    return count;
}

// Count how many recorded status messages contain a given substring.
size_t countStatusContaining(const PXR_NS::DffDiagnosticCollector& collector,
                             const std::string&                    bucketKey,
                             const std::string&                    needle) {
    size_t count = 0;
    for (const auto& msg : dffGetStatusMessages(collector, bucketKey)) {
        if (msg.find(needle) != std::string::npos) {
            ++count;
        }
    }
    return count;
}

// Returns the "points" attribute of the UsdGeomPoints prim generated by the
// Dynamic Payload at "/Root/geo/points". This is the animated attribute the
// query-time-sample tests resolve at various times. The returned attribute is
// invalid if the prim is absent or not a UsdGeomPoints (e.g. the payload failed
// to load), so callers should check it before use.
PXR_NS::UsdAttribute pointsAttrOf(PXR_NS::UsdStageRefPtr& stage) {
    using namespace PXR_NS;
    return UsdGeomPoints{stage->GetPrimAtPath(SdfPath{"/Root/geo/points"})}
        .GetPointsAttr();
}

