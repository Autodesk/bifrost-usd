// Tests validating that the layer generated by the Bifrost Dynamic Payload is
// read-only. The DFF plugin produces its contents lazily and has no asset to
// write back to, so BifrostDynamicFileFormat::Read marks the generated layer
// non-editable and non-savable. These tests assert those permissions and that a
// direct authoring attempt on the layer is rejected.

#include <gtest/gtest.h>

// DFF test helpers
#include "dffTestDiagnostics.h"
#include "dffTestLayerHelpers.h"

// Bifrost USD
#include <utils/test/testUtils.h>

// Open USD
#include <pxr/base/tf/errorMark.h>
#include <pxr/pxr.h>
#include <pxr/usd/sdf/layer.h>
#include <pxr/usd/sdf/path.h>
#include <pxr/usd/sdf/primSpec.h>
#include <pxr/usd/usd/stage.h>

using namespace BifrostUsd::TestUtils;
using namespace DffTestHelpers;

namespace {
UniqueTestOutputSubdir g_OutputDir{"testFileFormat_readOnlyLayer",
                                   true /*autoDelete*/};

// A simple static-mesh compound whose "mesh" output port resolves cleanly, so
// the generated payload layer is guaranteed to be composed into the stage.
constexpr const char* kCompound   = "Test::DynamicFileFormat::create_mesh_cube";
constexpr const char* kOutputPort = "mesh";
} // namespace

PXR_NAMESPACE_OPEN_SCOPE

// The generated payload layer is created neither editable nor savable.
TEST(ReadOnlyLayer, payload_layer_is_read_only) {
    DffDiagnosticCollector collector;
    constexpr auto         bucketKey = "payload_layer_is_read_only";

    auto stage = createStageWithCompoundPayload(kCompound, kOutputPort, bucketKey,
                                                g_OutputDir);
    ASSERT_TRUE(stage);

    auto payloadLayer = getGeneratedPayloadLayer(stage);
    ASSERT_TRUE(payloadLayer) << "Generated Bifrost Dynamic Payload layer not "
                                 "found in the stage's used layers";

    EXPECT_FALSE(payloadLayer->PermissionToEdit());
    EXPECT_FALSE(payloadLayer->PermissionToSave());

    EXPECT_TRUE(dffHasNoError(collector, bucketKey));
}

// Attempting to author on the read-only payload layer is rejected: the spec is
// not created, the layer is not mutated, and USD posts an error.
TEST(ReadOnlyLayer, authoring_on_payload_layer_is_rejected) {
    DffDiagnosticCollector collector;
    constexpr auto         bucketKey = "authoring_on_payload_layer_is_rejected";

    auto stage = createStageWithCompoundPayload(kCompound, kOutputPort, bucketKey,
                                                g_OutputDir);
    ASSERT_TRUE(stage);

    auto payloadLayer = getGeneratedPayloadLayer(stage);
    ASSERT_TRUE(payloadLayer);

    // The probe prim must not already exist before we attempt to create it.
    ASSERT_FALSE(payloadLayer->HasSpec(SdfPath{"/ReadOnlyProbe"}));

    SdfPrimSpecHandle spec =
        SdfPrimSpec::New(payloadLayer, "ReadOnlyProbe", SdfSpecifierDef);

    EXPECT_FALSE(spec) << "Authoring on a read-only payload layer must fail";
    EXPECT_FALSE(payloadLayer->HasSpec(SdfPath{"/ReadOnlyProbe"}))
        << "The rejected authoring attempt must not mutate the layer";

    dffHasNoError(collector, bucketKey); // no DFF errors expected
}

